#: Every shape `AcoustID:` takes at column 0, from source:
#: `cyanrip@aa45b975:src/cyanrip_log.c:1016-1020` (start report) and
#: `cyanrip@aa45b975:src/acoustid.c:299` and `:348` (after the rip), with the
#: format's `%i`/`%s` filled in.
_ACOUSTID_SHAPES = (
    "AcoustID:       unsupported (built without libchromaprint)",
    "AcoustID:       disabled",
    "AcoustID:       fingerprinting, submitting accurate rips",
    "AcoustID:       fingerprinting, no user API key to submit with",
    "AcoustID: submitted 12 fingerprints, pending import",
    "AcoustID: 1 fingerprint saved to tags, not submitted: not every track has a "
    "MusicBrainz recording",
)


def _classify_top_level(line: str) -> str | None:
    """What recognises this column-0 line, or None — the completeness sweep's lookup.

    The same three-way lookup `tests/test_parsers_cyanrip_log.py` runs over
    `output_reference/`: line rules, section patterns, written-down ignores.
    """
    for rule in cyanrip_log._ALL_LINE_RULES:
        if rule.pattern.match(line):
            return rule.name
    for name, pattern in cyanrip_log._SECTION_LINE_PATTERNS:
        if pattern.match(line):
            return name
    if cyanrip_log._is_ignored_disc_line(line):
        return "ignored"
    return None


def _unaccounted(text: str) -> list[str]:
    return [
        line
        for line in text.splitlines()
        if line and not line[0].isspace() and _classify_top_level(line) is None
    ]


# --- 1. the two new disc lines -------------------------------------------------


def test_every_column_zero_line_of_the_rc3_start_report_is_accounted_for() -> None:
    """The completeness sweep's question, asked of `.23`'s real start report.

    `test_every_top_level_line_of_the_real_cyanrip_logs_is_accounted_for` reads
    only `output_reference/`, which holds no `.23` log, so on its own it could not
    see the two new lines. This is the same lookup over the real text that carries
    them. Floored, so it cannot pass by finding nothing.
    """
    lines = [line for line in _RC3_START_REPORT.splitlines() if line]
    assert len(lines) >= 25, len(lines)
    assert "AccurateRip ID: 00000672-0000130b-14000603" in lines
    assert "AcoustID:       unsupported (built without libchromaprint)" in lines
    assert _unaccounted(_RC3_START_REPORT) == []


def test_the_accuraterip_id_is_parsed_from_the_real_line() -> None:
    """Parsed, not ignored: it is the key the AccurateRip request was made under.

    Its third word is the CDDB ID, which the same report states on its own line,
    so the two readings of one artifact are checked against each other here.
    """
    parsed = parse_cyanrip_log(_RC3_START_REPORT)
    assert parsed.accuraterip_disc_id == "00000672-0000130b-14000603"
    assert parsed.cddb_id == "14000603"
    assert parsed.accuraterip_disc_id.rsplit("-", 1)[1] == parsed.cddb_id.lower()


def test_the_accuraterip_id_is_lower_cased_and_absent_means_absent() -> None:
    """`%08x` prints lower case; an upper-case line is the same ID, not a new one.

    And a log with no such line, which is every build before `.23`, records "",
    never a zero ID.
    """
    upper = parse_cyanrip_log(
        "cyanrip 0.9.4\nAccurateRip ID: 00000672-0000130B-14000603\n"
    )
    assert upper.accuraterip_disc_id == "00000672-0000130b-14000603"
    assert parse_cyanrip_log("cyanrip 0.9.3 (release)\n").accuraterip_disc_id == ""


