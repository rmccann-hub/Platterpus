    upper = parse_cyanrip_log(
        "cyanrip 0.9.4\nAccurateRip ID: 00000672-0000130B-14000603\n"
    )
    assert upper.accuraterip_disc_id == "00000672-0000130b-14000603"
    assert parse_cyanrip_log("cyanrip 0.9.3 (release)\n").accuraterip_disc_id == ""


