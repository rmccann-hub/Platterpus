def _classify_top_level(line: str) -> str | None:
    """What recognises this column-0 line, or None — the completeness sweep's lookup.

    The same three-way lookup `tests/test_parsers_cyanrip_log.py` runs over
    `output_reference/`: line rules, section patterns, written-down ignores.
    """
    for rule in cyanrip_log._ALL_LINE_RULES:
        if rule.pattern.match(line):
            return rule.name
    for name, pattern in cyanrip_log._SECTION_LINE_PATTERNS:
        if pattern.match(line):
            return name
    if cyanrip_log._is_ignored_disc_line(line):
        return "ignored"
    return None


def _unaccounted(text: str) -> list[str]:
    return [
        line
        for line in text.splitlines()
        if line and not line[0].isspace() and _classify_top_level(line) is None
    ]


