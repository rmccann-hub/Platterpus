"""The parser, ready for the fork's `+platterpus.23` (upstream cyanrip 0.9.4-rc3).

## Why this file exists

The fork merged upstream rc3 and will not release `.23` until our parser accepts
what rc3 adds to the log (their sync analysis §4,
`cyanrip@aa45b975:docs/upstream/sync-2026-10-12-rc3.md`: *"their
parser should accept the two new disc lines and the data-track rows before a
release of ours carries them"*). Every shape below is derived from THEIR SOURCE at
the tip that carries the merge, `cyanrip@aa45b975`, never from the analysis's
prose, and each test names the line it was read from.

Two kinds of input, said plainly so nobody mistakes one for the other:

* **Real emitted text.** The `AccurateRip ID:` and `AcoustID:` lines, and the
  start report they sit in, are copied verbatim from the golden reference the
  fork regenerated with that build (`cyanrip@aa45b975:docs/golden-reference.log`,
  generated by `3b9d670`).
* **Constructed from the format strings.** No committed log of theirs carries a
  data track: their image tests (`tests/rip_images.py`, `sc_mixed`,
  `sc_data_track_completed`) rip one in CI and keep only assertions. So the data
  track blocks here are built line by line from `cyanrip_log_track_end()`
  (`cyanrip@aa45b975:src/cyanrip_log.c:530-563`) and the data-track ripper
  (`cyanrip@aa45b975:src/cyanrip_main.c:1197-1313`). The first real `.23` log
  with a data track should replace them; until then this is a stand-in, and what
  it does that the real thing may not is listed in `_DATA_BLOCK`'s comment.
"""

