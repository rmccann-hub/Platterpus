#: A copied data track's block, from the format strings, `{n}` its number.
#:
#: Order and indentation from `cyanrip@aa45b975:src/cyanrip_main.c:1296` (opener),
#: `:1267` (outcome), then `cyanrip_log_track_end()`:
#: `src/cyanrip_log.c:510-512` (`Preemphasis:`), `:530-537` (`Properties:`,
#: `Data bytes:`, `Frames:`, then `print_offsets()`'s `Start LSN:`/`End LSN:`),
#: `:540-547` (`CRC32:`, `Sector EDC:`), `:551-556` (`File(s):` and one path per
#: output format, `CRIP_PATH_DATA`, so `.bin`).
#:
#: What this stand-in does that a real log may not: it prints no `Pregap LSN:`
#: row, which `print_offsets()` prints when the track has a pregap; it prints one
#: `File(s):` path (one per `-o` format in reality, and we send one); and the
#: progress line the copier prints goes to stdout only (`cyanrip_log(NULL, …)`,
#: `src/cyanrip_main.c:941` and `:1001`), so it is correctly absent.
_DATA_BLOCK = """\
Track {n} is data:
Track {n} ripped successfully!
  Preemphasis:   none detected

  Properties:
    Data bytes:  352800 (0.34 Mib)
    Frames:      150
    Start LSN:   {start}
    End LSN:     {end}

  CRC32:         1A2B3C4D
  Sector EDC:    all 150 sectors match

  File(s):
    o/{n}.bin

"""

#: An audio track's block in the `.14`+ wording, cut to the rows the checks read.
_AUDIO_BLOCK = """\
Track {n} read successfully!
  Preemphasis:   none detected

  Properties:
    Duration:    00:02.00
    Samples:     88200
    Frames:      150
    Start LSN:   {start}
    End LSN:     {end}

  EAC CRC32:     0000000{n}
  Secure re-read:  not attempted
  Accurip:       disc found in database (max confidence: 5)
    Accurip v1:  1111111{n} (accurately ripped, confidence 5)
    Accurip v2:  2222222{n} (accurately ripped, confidence 5)

  File(s):
    o/{n}.flac

"""

_FOOTER = """\
Tracks ripped accurately: 2/3
Ripping errors: 0
Encoder errors: none; 2 tracks encoded
Read stalls:    none (no read exceeded 10s)
Rip completed:  yes (3 of 3 tracks)
Ripping finished at 2026-10-14T00:10:22+00:00
"""


def _mixed_disc(data_block: str = _DATA_BLOCK) -> str:
    """Upstream's `mixed.cue` shape: a data track 1, then audio tracks 2 and 3."""
    return (
        _RC3_START_REPORT
        + "\nTracks:\n\n"
        + data_block.format(n=1, start=0, end=149)
        + _AUDIO_BLOCK.format(n=2, start=150, end=299)
        + _AUDIO_BLOCK.format(n=3, start=300, end=449)
        + _FOOTER
    )


def _trailing_disc(opener: str) -> str:
    """Upstream's `trailing.cue` shape: audio 1 and 2, then a data track 3.

    `opener` is the data track's first line, so the same disc can be written the
    way `-X` writes it (`Track 3 is data, skipping:`, and then no outcome, CRC or
    file: `cyanrip@aa45b975:src/cyanrip_main.c:1294`, `src/cyanrip_log.c:539`
    and `:550` are all skipped).
    """
    return (
        "cyanrip 0.9.4-rc3+platterpus.23 (platterpus-fork-g3b9d670)\n"
        "\nTracks:\n\n"
        + _AUDIO_BLOCK.format(n=1, start=0, end=149)
        + _AUDIO_BLOCK.format(n=2, start=150, end=299)
        + f"{opener}\n"
        "  Preemphasis:   none detected\n"
        "\n"
        "  Properties:\n"
        "    Data bytes:  352800 (0.34 Mib)\n"
        "    Frames:      150\n"
        "    Start LSN:   11700\n"
        "    End LSN:     11849\n"
        "\n"
        "Rip completed:  yes (2 of 3 tracks)\n"
    )


def test_a_copied_data_track_is_its_own_track_and_touches_no_audio_track() -> None:
    """The headline: a data track never becomes, or bleeds into, an audio track."""
    parsed = parse_cyanrip_log(_mixed_disc())
    assert [t.number for t in parsed.tracks] == [1, 2, 3]
    data, *audio = parsed.tracks
    assert data.status == DATA_TRACK_COPIED
    assert data.data_crc32 == "1A2B3C4D"
    assert data.data_sector_edc == "all 150 sectors match"
    assert data.filename == "o/1.bin"
    assert (data.start_sector, data.end_sector) == (0, 149)
    # Its CRC is not an audio CRC: nothing that tallies audio may see it.
    assert data.copy_crc == ""
    assert data.accuraterip_v1 is None and data.accuraterip_v2 is None
    for track, number in zip(audio, (2, 3), strict=True):
        assert track.status == "ripped successfully"
        assert track.copy_crc == f"0000000{number}"
        assert track.data_crc32 == "" and track.data_sector_edc == ""
        assert track.filename == f"o/{number}.flac"
    assert (audio[0].start_sector, audio[1].end_sector) == (150, 449)
    assert parsed.rip_completed_tracks == 3 and parsed.rip_completed_total == 3
    assert not parsed.log_truncated and not parsed.last_track_incomplete


def test_every_column_zero_line_of_a_data_track_disc_is_accounted_for() -> None:
    """The completeness sweep over a whole `.23` mixed disc, failures included."""
    with_errors = _DATA_BLOCK.replace(
        "Track {n} ripped successfully!",
        "\nSector EDC mismatch at LSN 10!\n"
        "\nFrame read failed at LSN 11!\n"
        'Error writing to "o/{n}.bin": No space left on device!\n'
        "Track {n} ripped with errors.",
    )
    text = _mixed_disc(with_errors)
    top_level = [line for line in text.splitlines() if line and not line[0].isspace()]
    assert len(top_level) >= 35, len(top_level)
    assert _unaccounted(text) == []


def test_a_skipped_trailing_data_track_does_not_overwrite_the_last_audio_track() -> (
    None
):
    """`is data, skipping:` must open a block, or its rows land in track 2's.

    Measured before the arm existed: track 2 ended up with the data track's
    `Start LSN: 11700` / `End LSN: 11849`, and the disc had two tracks.
    """
    parsed = parse_cyanrip_log(_trailing_disc("Track 3 is data, skipping:"))
    assert [t.number for t in parsed.tracks] == [1, 2, 3]
    assert (parsed.tracks[1].start_sector, parsed.tracks[1].end_sector) == (150, 299)
    assert parsed.tracks[2].status == DATA_TRACK_SKIPPED
    assert (parsed.tracks[2].start_sector, parsed.tracks[2].end_sector) == (
        11700,
        11849,
    )


def test_an_older_builds_data_track_still_reads_as_skipped() -> None:
    """Archival logs parse exactly as before: `is data:` with nothing after it.

    Every build before `.23` printed `Track N is data:` and copied nothing
    (`cyanrip@200530e2:src/cyanrip_main.c:886-889`), so its block carries no
    outcome, no `CRC32:` and no file.
    """
    parsed = parse_cyanrip_log(_trailing_disc("Track 3 is data:"))
    assert parsed.tracks[2].status == DATA_TRACK_SKIPPED
    assert parsed.tracks[2].filename == ""


def test_a_copy_with_sector_errors_says_so() -> None:
    """`ripped with errors.` plus the EDC row's mismatch count, verbatim."""
    block = _DATA_BLOCK.replace(
        "Track {n} ripped successfully!",
        "\nSector EDC mismatch at LSN 10!\nTrack {n} ripped with errors.",
    ).replace("all 150 sectors match", "1 of 150 sectors mismatched")
    data = parse_cyanrip_log(_mixed_disc(block)).tracks[0]
    assert data.status == DATA_TRACK_COPIED_WITH_ERRORS
    assert data.data_sector_edc == "1 of 150 sectors mismatched"


def test_a_copy_that_failed_before_its_outcome_is_not_called_skipped() -> None:
    """A `.23` copy that died writing the `.bin`: diagnostic, then no outcome.

    The block's only witness of the attempt is the copier's own message
    (`cyanrip@aa45b975:src/cyanrip_main.c:1243`, then `goto end` with no outcome).
    Reading it as `skipped` would claim the older builds' behaviour for a copy
    that was tried and failed.
    """
    block = (
        "Track {n} is data:\n"
        '\nError writing to "o/{n}.bin": No space left on device!\n'
        "Error ripping: No space left on device\n"
    )
    data = parse_cyanrip_log(_mixed_disc(block)).tracks[0]
    assert data.status == DATA_TRACK_COPY_NOT_COMPLETED


@pytest.mark.parametrize(
    ("where", "expected"),
    [
        ("track 3, mid-read", DATA_TRACK_COPY_NOT_COMPLETED),
        ("between tracks, no read in progress", DATA_TRACK_SKIPPED),
        ("track 2, mid-read", DATA_TRACK_SKIPPED),  # names another track
    ],
)
def test_an_interrupted_copy_is_told_apart_from_a_skip(
    where: str, expected: str
) -> None:
    """A signal mid-copy leaves `is data:` and nothing else in the block.

    The footer's `Interrupted at: track N, mid-read` is the fact that settles it,
    and it arrives after the block, so it is applied after the loop. It moves only
    the track it names.
    """
    text = (
        _trailing_disc("Track 3 is data:").replace(
            "Rip completed:  yes (2 of 3 tracks)\n", ""
        )
        + "Stopping, ripping incomplete!\n"
        + "Rip completed:  no (interrupted by SIGTERM, 2 of 3 tracks)\n"
        + f"Interrupted at: {where}\n"
    )
    parsed = parse_cyanrip_log(text)
    assert parsed.tracks[2].status == expected
    assert parsed.tracks[1].status == "ripped successfully"


