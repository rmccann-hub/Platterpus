def _load_generator() -> ModuleType:
    """Import the script by path — ``scripts/`` is not an importable package."""
    spec = importlib.util.spec_from_file_location("emit_bom", _SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def generator() -> ModuleType:
    return _load_generator()


@pytest.fixture(scope="module")
def committed() -> dict[str, object]:
    data = json.loads(_BOM.read_text(encoding="utf-8"))
    assert isinstance(data, dict)
    return data


def _components(bom: dict[str, object]) -> list[dict[str, object]]:
    items = bom["components"]
    assert isinstance(items, list)
    return items


def _services(bom: dict[str, object]) -> list[dict[str, object]]:
    items = bom["services"]
    assert isinstance(items, list)
    return items


def _props(item: dict[str, object]) -> dict[str, str]:
    props = item.get("properties", [])
    assert isinstance(props, list)
    return {str(p["name"]): str(p["value"]) for p in props}


