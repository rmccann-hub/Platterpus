"""`bom.cdx.json` and its block in `DEPENDENCIES.md` must be what the code says today.

The maintainer asked (2026-10-05) for *"a full map out of what projects /
languages / versions / applications / dependencies you have or rely on"*, kept
*"somewhere standard that you and other applications can see and use"*. The map
is a CycloneDX 1.7 BOM plus a human-readable block, both GENERATED by
``scripts/emit_bom.py`` from the code that enforces each fact. A hand-kept map
is only ever wrong by omission, and nobody reviews a document for what is not in
it — so this file is what makes the promise checkable:

* **staleness** — the committed JSON and the committed Markdown block are
  byte-identical to a fresh run (same mechanism as
  ``tests/test_dependency_contract_emitted.py``);
* **determinism** — a run under a different ``HOME`` and hash seed produces the
  same bytes, so the staleness check cannot fail at random;
* **non-triviality** — floors, and named members that must be present, because
  "the file equals the generator" is satisfied perfectly by an empty generator;
* **coverage, checked independently** — every pyproject dependency, every
  registry entry, every GitHub Action pin and every tool the code looks up is
  re-derived HERE by a different method (plain text and ``tomllib``, not the
  generator's AST walkers) and required in the BOM, because two implementations
  sharing one ancestor share its bugs;
* **structure** — CycloneDX's shape, asserted field by field. **This is not
  JSON-schema validation**: no schema validator is a dependency of this project,
  and adding one needs the maintainer's approval. The assertions below cover
  every field the generator writes.

Regenerate with ``python3 scripts/emit_bom.py``.
"""

