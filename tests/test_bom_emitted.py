def test_the_map_is_not_empty(generator: ModuleType, committed: dict) -> None:
    """Floors. Every assertion above is "the file matches the generator", which
    an empty generator satisfies."""
    components = _components(committed)
    services = _services(committed)
    assert len(components) >= _MIN_COMPONENTS, len(components)
    assert len(services) >= _MIN_SERVICES, len(services)
    by_category: dict[str, int] = {}
    for item in [*components, *services]:
        category = _props(item)["platterpus:category"]
        by_category[category] = by_category.get(category, 0) + 1
    expected = {key for key, _title in generator.CATEGORIES}
    assert set(by_category) == expected, set(by_category) ^ expected
    assert by_category["host-tool"] >= _MIN_HOST_TOOLS
    assert by_category["ci-action"] >= _MIN_ACTIONS


