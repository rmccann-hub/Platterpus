def test_the_cyanrip_fork_is_present_at_the_current_pin(committed: dict) -> None:
    from platterpus.deps import fork_source

    repo = fork_source.FORK_REPO_URL.removesuffix(".git")
    slug = repo.removeprefix("https://github.com/")
    forks = [
        c
        for c in _components(committed)
        if c.get("purl") == f"pkg:github/{slug}@{fork_source.FORK_PIN}"
    ]
    assert len(forks) == 1, "the production fork pin is not in the BOM"
    fork = forks[0]
    assert fork["version"] == fork_source.FORK_EXPECTED_VERSION
    assert fork["scope"] == "required"
    props = _props(fork)
    assert props["platterpus:pin"] == fork_source.FORK_PIN
    assert props["platterpus:build-tag"] == fork_source.FORK_EXPECTED_BUILD_TAG
    assert fork_source.PIN_UNDER_REVIEW in props["platterpus:pin-under-review"]
    refs = fork["externalReferences"]
    assert isinstance(refs, list)
    assert any(r["type"] == "vcs" and r["url"].startswith(repo) for r in refs)
    # The shared seam texts travel with the partner project.
    docs = {r["url"].rsplit("/", 1)[1] for r in refs if r["type"] == "documentation"}
    assert {"handshake-protocol.md", "seam-rules.md"} <= docs, docs
    # The fork's ancestor is upstream cyanrip.
    ancestors = fork["pedigree"]["ancestors"]
    assert [a["purl"] for a in ancestors] == ["pkg:github/cyanreg/cyanrip"]


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _requirement_name(text: str) -> str:
    match = re.match(r"\s*([A-Za-z0-9][A-Za-z0-9._-]*)", text)
    assert match, text
    return _norm(match.group(1))


def test_every_pyproject_dependency_is_present(committed: dict) -> None:
    """Re-read with ``tomllib`` here, not through the generator."""
    pyproject = tomllib.loads((REPO_ROOT / "pyproject.toml").read_text("utf-8"))
    project = pyproject["project"]
    wanted = {
        "required": [_requirement_name(d) for d in project["dependencies"]],
        "excluded": [
            *(_requirement_name(d) for d in project["optional-dependencies"]["dev"]),
            *(_requirement_name(d) for d in pyproject["build-system"]["requires"]),
        ],
    }
    assert len(wanted["required"]) >= 5 and len(wanted["excluded"]) >= 6
    present = {
        str(c["purl"]).removeprefix("pkg:pypi/").split("@")[0]: c["scope"]
        for c in _components(committed)
        if str(c.get("purl", "")).startswith("pkg:pypi/")
    }
    for scope, names in wanted.items():
        for name in names:
            assert name in present, f"{name} (pyproject) is missing from the BOM"
            assert present[name] == scope, f"{name}: scope {present[name]} != {scope}"


