def test_a_tool_the_code_uses_without_a_note_stops_the_run(
    generator: ModuleType, monkeypatch: pytest.MonkeyPatch
) -> None:
    """A new ``resolve_tool("x")`` must not slip into the code unmapped."""
    tool_entries = sys.modules["bommap.tool_entries"]
    real = dict(tool_entries.tool_lookups())
    monkeypatch.setattr(
        tool_entries,
        "tool_lookups",
        lambda: {**real, "frobnicate": ("src/platterpus/app.py",)},
    )
    with pytest.raises(generator.GeneratorError, match="frobnicate"):
        tool_entries._host_tool_entries()


def test_a_note_for_a_tool_the_code_no_longer_uses_stops_the_run(
    generator: ModuleType, monkeypatch: pytest.MonkeyPatch
) -> None:
    """…and a tool the code stopped using must not linger in the map."""
    tool_entries = sys.modules["bommap.tool_entries"]
    notes = dict(tool_entries._TOOL_NOTES)
    notes["retired-tool"] = tool_entries._ToolNote("used to do something")
    monkeypatch.setattr(tool_entries, "_TOOL_NOTES", notes)
    with pytest.raises(generator.GeneratorError, match="retired-tool"):
        tool_entries._host_tool_entries()


def test_a_witness_that_no_longer_holds_stops_the_run(generator: ModuleType) -> None:
    reading = sys.modules["bommap.reading"]
    with pytest.raises(generator.GeneratorError, match="no longer a string"):
        reading._require(
            "src/platterpus/app.py", "no-such-program-anywhere", why="probe"
        )
    # And holds where it should: `bash` is what --rig-session runs.
    assert reading._require("src/platterpus/app.py", "bash", why="probe")
