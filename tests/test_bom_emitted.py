# --- Structure (in place of schema validation) ----------------------------------------


def test_the_structure_holds(committed: dict) -> None:
    components = _components(committed)
    services = _services(committed)
    metadata = committed["metadata"]
    refs = [str(c["bom-ref"]) for c in [*components, *services]]
    refs.append(str(metadata["component"]["bom-ref"]))
    assert len(refs) == len(set(refs)), "bom-refs must be unique"
    known = set(refs)

    for c in components:
        where = c["bom-ref"]
        assert set(c) <= _COMPONENT_KEYS, (where, set(c) - _COMPONENT_KEYS)
        assert c["type"] in _COMPONENT_TYPES, where
        assert isinstance(c["name"], str) and c["name"], where
        assert c["scope"] in _SCOPES, where
        # Mutually exclusive, and a range only on an external component.
        assert not ("version" in c and "versionRange" in c), where
        if "versionRange" in c:
            assert c.get("isExternal") is True, where
            assert str(c["versionRange"]).startswith("vers:"), where
        if "purl" in c:
            assert str(c["purl"]).startswith("pkg:"), where
            assert " " not in str(c["purl"]), where
    for s in services:
        where = s["bom-ref"]
        assert set(s) <= _SERVICE_KEYS, (where, set(s) - _SERVICE_KEYS)
        for endpoint in s.get("endpoints", []):
            assert re.match(r"^https?://[^\s{}]+$", endpoint), (where, endpoint)
        for flow in s.get("data", []):
            assert flow["flow"] in _FLOWS, where
            assert flow["classification"], where
        assert isinstance(s["authenticated"], bool)
    for item in [*components, *services]:
        for ref in item.get("externalReferences", []):
            assert ref["type"] in _REF_TYPES, (item["bom-ref"], ref)
            assert re.match(r"^https?://[^\s{}]+$", ref["url"]), ref
        for prop in item["properties"]:
            assert set(prop) == {"name", "value"}, prop
            assert isinstance(prop["value"], str), prop
            # Our own namespace; `cdx:` is CycloneDX's.
            assert prop["name"].startswith("platterpus:"), prop
    graph = committed["dependencies"]
    assert isinstance(graph, list) and len(graph) >= 5
    for edge in graph:
        assert set(edge) == {"ref", "dependsOn"}, edge
        assert edge["ref"] in known, edge["ref"]
        assert set(edge["dependsOn"]) <= known, set(edge["dependsOn"]) - known
    roots = [e for e in graph if e["ref"] == "platterpus"]
    assert len(roots) == 1 and len(roots[0]["dependsOn"]) >= 20


def test_the_markdown_and_the_json_describe_the_same_entries(committed: dict) -> None:
    """The relation between the two committed artifacts, checked on the files
    themselves rather than on the generator that wrote both."""
    document = _DEPENDENCIES.read_text(encoding="utf-8")
    block = document.split("<!-- BEGIN GENERATED: emit_bom.py", 1)[1]
    block = block.split("<!-- END GENERATED: emit_bom.py -->", 1)[0]
    components = _components(committed)
    services = _services(committed)
    assert f"**{len(components)} components and {len(services)} services**" in block
    for c in components:
        props = _props(c)
        label = (
            f"{c['group']}/{c['name']}"
            if props["platterpus:category"] == "ci-action"
            else c["name"]
        )
        assert f"| `{label}` |" in block, f"{label} is in the JSON, not the table"
    for s in services:
        assert f"| `{s['name']}` |" in block, s["name"]


def test_no_generated_row_can_be_mistaken_for_the_hand_kept_cyanrip_row() -> None:
    """``test_no_stale_version_claims`` finds THE cyanrip row by the prefix
    ``| cyanrip (``. The generated tables put every name in backticks so their
    cyanrip rows can never match that selector and be counted as a second one."""
    document = _DEPENDENCIES.read_text(encoding="utf-8")
