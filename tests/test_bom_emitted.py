def test_a_run_elsewhere_produces_the_same_bytes(tmp_path: Path) -> None:
    """Determinism, measured where it could fail: another process, another
    ``HOME`` (the registry's binary paths are computed from it) and another hash
    seed (set iteration order). A cached second call in this process would prove
    nothing. Also asserts the run writes nothing into ``HOME``."""
    env = {**os.environ, "HOME": str(tmp_path), "PYTHONHASHSEED": "4242"}
    run = subprocess.run(
        [sys.executable, str(_SCRIPT), "--stdout"],
        env=env,
        capture_output=True,
        text=True,
        timeout=180,
        check=False,
    )
    assert run.returncode == 0, run.stderr
    assert run.stdout == _BOM.read_text(encoding="utf-8"), (
        "the generator's output depends on the machine or on hash order"
    )
    assert not list(tmp_path.iterdir()), "the generator wrote into HOME"


def test_check_mode_can_fail_not_only_pass(
    generator: ModuleType, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """``--check`` must be able to return 1 for EITHER output going stale."""
    assert generator.main(["--check"]) == 0

    monkeypatch.setattr(generator, "OUTPUT_PATH", tmp_path / "absent.json")
    assert generator.main(["--check"]) == 1
    monkeypatch.undo()

    stale_doc = tmp_path / "DEPENDENCIES.md"
    stale_doc.write_text(
        _DEPENDENCIES.read_text(encoding="utf-8").replace(
            "| Category | Entries |", "| Category | Count |"
        ),
        encoding="utf-8",
    )
    monkeypatch.setattr(generator, "MARKDOWN_PATH", stale_doc)
    assert generator.main(["--check"]) == 1


